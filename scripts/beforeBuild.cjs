'use strict';

/**
 * beforeBuild.cjs — Pre-build hook for electron-builder.
 *
 * Runs before packaging:
 *   1. Rebuild native modules (argon2, node-pty) for the target Electron version
 *   2. Verify icon files exist
 *   3. Generate placeholder icons if missing (dev builds only)
 */

const { execSync }   = require('child_process');
const { existsSync, writeFileSync, mkdirSync, readFileSync } = require('fs');
const path           = require('path');

/**
 * electron-builder's `beforeBuild` hook (unlike `afterPack`) is called BEFORE
 * app.asar exists and receives { appDir, electronVersion, platform, arch } —
 * not { appOutDir, packager }. There is no `packager` object at this point, so
 * `context.packager.projectDir` always threw here. `appDir` is the project
 * root (same thing `packager.projectDir` would have resolved to), so use that.
 * See https://www.electron.build/docs/api/app-builder-lib.Interface.Hooks
 *
 * WHO CALLS THIS. `scripts/buildInstaller.cjs`, directly, immediately before it invokes
 * electron-builder. NOT electron-builder itself: `build.npmRebuild` is false, and that branch
 * returns before the `beforeBuild` hook is resolved, so a configured hook would never run. The
 * config entry was removed rather than left in place looking active (Section 177).
 *
 * It must NEVER return false. See the note at the end of this function: electron-builder reads a
 * false return as "node_modules are being copied into the package by someone else" and then
 * packages none of them.
 */
module.exports = async function(context) {
  const { appDir, platform } = context;
  const root = appDir;

  console.log('\n⬢ Rāma AGI — Pre-build checks...\n');

  // ── Check icon files ────────────────────────────────────────────────────────
  const assetsDir = path.join(root, 'assets');
  mkdirSync(assetsDir, { recursive: true });

  // If source logo exists but icons haven't been generated yet, generate them
  const sourceLogo = path.join(assetsDir, 'logo-source.png');
  const iconPng    = path.join(assetsDir, 'icon.png');
  if (existsSync(sourceLogo) && !existsSync(iconPng)) {
    console.log('  ⬢ logo-source.png found — auto-generating icons...');
    try {
      execSync('node scripts/generateIcons.cjs', { cwd: root, stdio: 'inherit' });
    } catch (e) {
      console.warn(`  ⚠ Icon auto-generation failed: ${e.message}`);
      console.warn('  ⚠ Run: npm install sharp png-to-ico png2icons --save-dev && npm run icons');
    }
  }

  const needed = {
    win32:  ['icon.ico'],
    darwin: ['icon.icns', 'icon.png'],
    linux:  ['icon.png'],
  };

  // `platform` here is builder-util's Platform enum object ({ name, ... }),
  // e.g. Platform.WINDOWS.name === 'windows' — not the Node.js `win32` you'd
  // get from `process.platform`. Map electron-builder's platform names to the
  // ones this table already uses.
  const platformKey = { windows: 'win32', mac: 'darwin', linux: 'linux' }[platform?.name] || 'linux';
  const icons        = needed[platformKey] || needed.linux;

  for (const icon of icons) {
    const iconPath = path.join(assetsDir, icon);
    if (!existsSync(iconPath)) {
      console.warn(`  ⚠ ${icon} not found in assets/ — using placeholder`);
      // Create a minimal placeholder so the build doesn't fail
      // Replace with a real 512x512 icon before distributing
      generatePlaceholderIcon(iconPath, icon);
    } else {
      console.log(`  ✓ ${icon} found`);
    }
  }

  // ── Check NSIS include file ─────────────────────────────────────────────────
  const nsisPath = path.join(assetsDir, 'installer.nsh');
  if (!existsSync(nsisPath)) {
    writeFileSync(nsisPath, '; Custom NSIS installer script\n; Generated by Rāma AGI build system\n');
  }

  // ── Rebuild native modules ──────────────────────────────────────────────────
  //
  // RESOLVED LOCALLY, NEVER THROUGH `npx` BY BARE NAME. This used to run
  // `npx electron-rebuild --force`, and once Section 173 replaced the deprecated
  // `electron-rebuild` package with its successor `@electron/rebuild`, npx stopped finding a local
  // match and DOWNLOADED the deprecated one mid-build instead — visible in the 2026-11-03
  // transcript as "The following package was not found and will be installed:
  // electron-rebuild@3.2.9", dragging the vulnerable tar@6.2.1 back in over the network.
  //
  // A build step that silently reaches the registry for a tool it was told not to use is worse
  // than one that stops, so the binary is resolved from the installed package and a missing one is
  // reported rather than fetched. This is also why `@electron/rebuild` stays a direct
  // devDependency even though electron-builder suggests removing it: we invoke it ourselves here,
  // and a transitive copy is not reliably resolvable.
  console.log('\n  ⬢ Rebuilding native modules for Electron...');
  try {
    // Read the manifest off disk rather than through `require.resolve`: @electron/rebuild declares
    // an `exports` map that does not expose './package.json', so resolving it that way throws
    // ERR_PACKAGE_PATH_NOT_EXPORTED. The directory is what we need, not a module specifier.
    const rebuildDir = path.join(root, 'node_modules', '@electron', 'rebuild');
    const manifest = path.join(rebuildDir, 'package.json');
    if (!existsSync(manifest)) {
      throw new Error(`@electron/rebuild is not installed at ${rebuildDir} — run npm install`);
    }
    const binRel = (JSON.parse(readFileSync(manifest, 'utf8')).bin || {})['electron-rebuild'];
    if (!binRel) throw new Error('@electron/rebuild declares no electron-rebuild binary');
    const binAbs = path.join(rebuildDir, binRel);
    execSync(`node "${binAbs}" --force`, { cwd: root, stdio: 'inherit' });
    console.log('  ✓ Native modules rebuilt\n');
    // RECORDED ON THE CONTEXT, not only printed. The caller owns this object, so this is how the
    // outcome reaches the build manifest and the closing report. Swallowing the failure in a
    // warning was why master could hold an installer whose build never mentioned it again.
    context.nativeRebuild = { ok: true, error: null };
  } catch (err) {
    console.warn(`  ⚠ electron-rebuild failed: ${err.message}`);
    console.warn('  ⚠ argon2 falls back to scrypt, node-pty to a piped shell — both work, both weaker');
    console.warn('  ⚠ On Windows this is usually the missing "MSVC v142 - VS 2019 C++ x64/x86');
    console.warn('  ⚠   Spectre-mitigated libs" component in the Visual Studio Installer\n');
    context.nativeRebuild = { ok: false, error: err.message };
  }

  // ── MUST RETURN TRUE. Returning false does not mean what it was taken to mean. ───────────────
  //
  // This used to `return false`, believing that it only told electron-builder "the native rebuild
  // is already done, skip yours". It does not. From `app-builder-lib/out/packager.js`:
  //
  //     // If beforeBuild resolves to false, it means that handling node_modules is done
  //     // outside of electron-builder.
  //     this._nodeModulesHandledExternally = !performDependenciesInstallOrRebuild;
  //
  // and `platformPackager.js` then reads that flag to decide whether to COLLECT node_modules AT
  // ALL:
  //
  //     if (!this.info.isPrepackedAppAsar && !this.info.areNodeModulesHandledExternally) {
  //       result = result.concat(await computeNodeModuleFileSets(this, moduleFileMatcher));
  //     }
  //
  // So `false` meant "I am copying node_modules into the package myself" — which nothing here was
  // doing. The consequence was an app.asar containing 241 app files and ZERO dependencies, built
  // and signed successfully, which `auditPackage.cjs` then refused to ship because
  // electron-updater, express, helmet, cors, express-rate-limit, systeminformation and argon2 were
  // all absent. Three build attempts were spent on this (Section 177).
  //
  // `npmRebuild: false` in the build config is NOT an alternative: that branch returns before
  // `beforeBuild` is resolved, so this hook — including the native rebuild above and the icon and
  // NSIS preparation — would not run at all.
  //
  // The cost of returning true is that electron-builder runs its own `installOrRebuild` pass after
  // this one. That is the duplicated work the old comment was trying to avoid, and it is the right
  // trade: a slower build beats an installer that cannot start. Consolidating onto a single rebuild
  // is a real improvement, but it is a change to how natives are produced and belongs in its own
  // tranche with a build to verify it — not bundled into the fix that unblocks packaging.
  return true;
};

function generatePlaceholderIcon(iconPath, filename) {
  // Write a minimal valid file so build doesn't crash
  // For ICO: minimal 1x1 pixel ICO header
  // For PNG: minimal 1x1 PNG
  // For ICNS: placeholder text
  const ext = path.extname(filename).toLowerCase();
  if (ext === '.ico') {
    // Minimal 1x1 ICO file (binary)
    const ico = Buffer.from([
      0x00,0x00, // reserved
      0x01,0x00, // type: icon
      0x01,0x00, // count: 1
      0x01,0x01, // width=1, height=1
      0x00,      // color count
      0x00,      // reserved
      0x01,0x00, // planes
      0x18,0x00, // bit count: 24
      0x28,0x00,0x00,0x00, // size of image data
      0x16,0x00,0x00,0x00, // offset to image data
      // BITMAPINFOHEADER (40 bytes)
      0x28,0x00,0x00,0x00,
      0x01,0x00,0x00,0x00,
      0x02,0x00,0x00,0x00,
      0x01,0x00, 0x18,0x00,
      0x00,0x00,0x00,0x00,
      0x08,0x00,0x00,0x00,
      0x00,0x00,0x00,0x00,
      0x00,0x00,0x00,0x00,
      0x00,0x00,0x00,0x00,
      0x00,0x00,0x00,0x00,
      // pixel data: violet #7700ff
      0xff,0x00,0x77, 0xff,0x00,0x77,
      0x00,0x00, // AND mask row
    ]);
    require('fs').writeFileSync(iconPath, ico);
  } else if (ext === '.png') {
    // Minimal 1x1 violet PNG
    const png = Buffer.from([
      0x89,0x50,0x4e,0x47,0x0d,0x0a,0x1a,0x0a,
      0x00,0x00,0x00,0x0d,0x49,0x48,0x44,0x52,
      0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x01,
      0x08,0x02,0x00,0x00,0x00,0x90,0x77,0x53,
      0xde,0x00,0x00,0x00,0x0c,0x49,0x44,0x41,
      0x54,0x08,0xd7,0x63,0xf8,0xcf,0xc0,0x00,
      0x00,0x00,0x02,0x00,0x01,0xe2,0x21,0xbc,
      0x33,0x00,0x00,0x00,0x00,0x49,0x45,0x4e,
      0x44,0xae,0x42,0x60,0x82,
    ]);
    require('fs').writeFileSync(iconPath, png);
  } else {
    require('fs').writeFileSync(iconPath, '# placeholder\n');
  }
  console.log(`  ⬢ Generated placeholder ${filename} (replace with real icon before distributing)`);
}
